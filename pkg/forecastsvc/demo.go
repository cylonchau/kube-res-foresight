// Names of the demo objects. Everything the demo creates carries one of them, so it can be recognised and
// removed without touching anything else.
const (
	DemoDatasourceName = "demo-synthetic"
	DemoModuleName     = "demo-shop"
	DemoNamespace      = "demo"
	DemoWorkload       = "shop"
	demoStepSeconds    = 300
	demoLookbackHours  = 14 * 24
	demoHorizonMin     = 60
	demoWarmupCycles   = 12
)

// demoSource is one metric source of the demo module: the preset it is made from and the role it plays.
type demoSource struct {
	kind, preset string
	stat         string
	weight       float64
	threshold    float64
	basis        string
	window       int
}

// demoSources are the metric sources of the demo module. The thresholds sit above what the synthetic workload reaches,
// so the pressure stays below one and the demo is not permanently over.
var (
	demoCPU    = demoSource{kind: "cpu", preset: "cadvisor.cpu.workload", stat: "p95", weight: 2, threshold: 3}
	demoMemory = demoSource{kind: "memory", preset: "cadvisor.memory.workload", stat: "p95", weight: 2, threshold: 12 * 1 << 30}
	demoRPS    = demoSource{kind: "rps", preset: "istio.rps.service", stat: "p95", weight: 3, threshold: 450}
	demoHeap   = demoSource{kind: "jvm_heap_used", preset: "micrometer.jvm.heap-used", stat: "p95", weight: 1}
)

// demoAux are measured, never forecast: the replica history the capacity is estimated from, the OOM protection, the
// heap pressure rule and the Kubernetes configuration.
var demoAux = []demoSource{
	{kind: "replicas", preset: "kube-state-metrics.replicas.ready", stat: "last", weight: 1, basis: model.BasisHistory, window: 6},
	{kind: "oom", preset: "cadvisor.oom.events", stat: "sum", weight: 1, threshold: 1, basis: model.BasisHistory, window: 24},
	{kind: "oom_working_set", preset: "cadvisor.oom.working-set", stat: "max", weight: 1, basis: model.BasisHistory, window: 24},
	{kind: "jvm_heap_max", preset: "micrometer.jvm.heap-max", stat: "max", weight: 1, basis: model.BasisHistory, window: 1},
	{kind: "jvm_threads", preset: "micrometer.jvm.threads", stat: "p95", weight: 1},
	{kind: "k8s_cpu_requests", preset: "kube-state-metrics.cpu.requests", stat: "last", weight: 1, basis: model.BasisHistory, window: 1},
	{kind: "k8s_mem_limits", preset: "kube-state-metrics.memory.limits", stat: "last", weight: 1, basis: model.BasisHistory, window: 1},
}

func demoModuleSources() []demoSource {
	return append([]demoSource{demoCPU, demoMemory, demoRPS, demoHeap}, demoAux...)
}

// demoAlgorithm is a platform algorithm the demo turns on, with parameters that suit its five-minute synthetic series.
type demoAlgorithm struct{ id, params string }

func demoAlgorithms() []demoAlgorithm {
	return []demoAlgorithm{
		{"seasonal_naive", seasonParams()},
		{"ewma", `{"alpha":0.3}`},
		{"holt_winters", fmt.Sprintf(`{"season_length_steps":%d}`, 86400/demoStepSeconds)},
		{"ridge_ar", `{"lags":12}`},
	}
}

// DemoResult reports what the demo created and what the first pipeline run produced.
type DemoResult struct {
	DatasourceID uint            `json:"datasource_id"`
	ModuleID     uint            `json:"module_id"`
	Mappings     map[string]uint `json:"mappings"`
	Created      bool            `json:"created"`
	Pipeline     *PipelineResult `json:"pipeline"`
	Backtests    int             `json:"backtests"`
	Evaluated    int             `json:"evaluated"`
	Warmup       int             `json:"warmup_cycles"`
}

// CreateDemo creates (or reuses) the demo datasource, the preset mappings and the demo module, turns on a few
// algorithms, then runs the whole pipeline once so every page has data: it replays a few earlier prediction cycles
// on the synthetic history so the predictions have measured actuals, then collects, predicts, backtests, evaluates
// and recommends at the present. Calling it again reuses the objects and refreshes the data.
func (s *Service) CreateDemo(ctx context.Context) (*DemoResult, error) {
	res := &DemoResult{Mappings: map[string]uint{}}

	ds, err := s.Datasources.ByName(ctx, DemoDatasourceName)
	if err != nil {
		return nil, err
	}
	if ds == nil {
		ds = &model.Datasource{
			Name: DemoDatasourceName, Type: model.DatasourceTypeDemo, BaseURL: "demo://synthetic", AuthType: model.DatasourceAuthNone,
			TimeoutSeconds: 30, MaxConcurrency: 1, Enabled: true, Status: model.DatasourceStatusOK, ServerVersion: "synthetic",
			Remark: "DEMO: synthetic data generated by the program, not measurements of any cluster.",
		}
		if err := s.Datasources.Create(ctx, ds); err != nil {
			return nil, err
		}
		res.Created = true
	}
	res.DatasourceID = ds.ID

	applied := map[string]bool{}
	for _, src := range demoModuleSources() {
		if applied[src.kind] {
			continue
		}
		applied[src.kind] = true
		p, err := preset.Get(src.preset)
		if err != nil {
			return nil, err
		}
		mapping, err := s.Mappings.ByName(ctx, ds.ID, p.ID)
		if err != nil {
			return nil, err
		}
		if mapping == nil {
			mapping = p.Mapping(ds.ID, p.ID, demoStepSeconds)
			if err := model.ValidateMetricMapping(mapping); err != nil {
				return nil, fmt.Errorf("preset %s: %w", p.ID, err)
			}
			if err := s.Mappings.Create(ctx, mapping); err != nil {
				return nil, err
			}
		}
		res.Mappings[src.kind] = mapping.ID
	}

	// the algorithms are platform-wide: the demo turns on the ones it needs and gives them parameters that fit its series
	if err := s.EnsureAlgorithms(ctx); err != nil {
		return nil, err
	}
	for _, a := range demoAlgorithms() {
		cfg, err := s.Algorithms.Get(ctx, a.id)
		if err != nil {
			return nil, err
		}
		if cfg.Enabled && cfg.Params != "" {
			continue // the administrator's own setting stays
		}
		canonical, err := ValidateParams(a.id, a.params)
		if err != nil {
			return nil, fmt.Errorf("demo algorithm %s: %w", a.id, err)
		}
		cfg.Enabled, cfg.Params = true, canonical
		if err := s.Algorithms.Save(ctx, cfg); err != nil {
			return nil, err
		}
	}

	// the module is the workload; every enabled algorithm applies to it automatically
	m, err := s.Modules.ByName(ctx, DemoModuleName)
	if err != nil && !errors.Is(err, gorm.ErrRecordNotFound) {
		return nil, err
	}
	if m == nil || errors.Is(err, gorm.ErrRecordNotFound) {
		m = &model.ForecastModule{
			Name: DemoModuleName, Description: "DEMO: synthetic workload, not a real service.", Enabled: true, Mode: model.ModeRecommend,
			Namespace: DemoNamespace, WorkloadKind: model.KindDeployment, Workload: DemoWorkload, Service: DemoWorkload, Container: "app", Timezone: "UTC", TTLSeconds: 900,
			LookbackHours: demoLookbackHours, HorizonMinutes: demoHorizonMin, MaxFillSteps: 3,
			MinReplicas: 2, MaxReplicas: 30, FallbackReplicas: 3, MinCPUMilli: 100, FallbackCPUMilli: 1000,
			HeadroomRatio: 1.2, PodCapacityRPS: demo.PodCapacityRPS,
			ReplicaMode: model.ReplicaModeDynamic, CapacityMode: model.CapacityModeEstimate,
			PodCPURequestMilli: int64(demo.PodCPUCores * 1000), TargetUtilization: demo.TargetUtil,
		}
		if err := m.Validate(); err != nil {
			return nil, err
		}
		if err := s.Modules.Create(ctx, m); err != nil {
			return nil, err
		}
		for k, src := range demoModuleSources() {
			ms := &model.MetricSource{ModuleID: m.ID, Name: src.preset, Kind: src.kind, MappingID: res.Mappings[src.kind], Resource: model.DefaultResource(src.kind),
				Stat: src.stat, Weight: src.weight, Threshold: src.threshold, Basis: src.basis, WindowHours: src.window, Priority: k, Enabled: true}
			if src.kind == "replicas" {
				ms.Resource = model.ResourceSignal
			}
			if err := ms.Validate(); err != nil {
				return nil, fmt.Errorf("demo source %s: %w", src.kind, err)
			}
			if err := s.Modules.SaveSource(ctx, ms); err != nil {
				return nil, err
			}
		}
		res.Created = true
	}
	res.ModuleID = m.ID

	// Replay earlier prediction cycles on a copy of the service whose clock is set back, so the predictions of
	// the last hours exist and can be scored against the actuals collected afterwards.
	now := s.now()
	// (a copy of the settings of the service, not of its locks)
	sim := &Service{Modules: s.Modules, Algorithms: s.Algorithms, Mappings: s.Mappings, Datasources: s.Datasources, Samples: s.Samples, Config: s.Config,
		Predictions: s.Predictions, RunStates: s.RunStates, Telemetry: s.Telemetry, NewQuerier: s.NewQuerier, Now: s.Now, FetchOptions: s.FetchOptions}
	for cycle := demoWarmupCycles; cycle >= 1; cycle-- {
		at := now.Add(-time.Duration(cycle) * time.Duration(demoHorizonMin) * time.Minute)
		sim.Now = func() time.Time { return at }
		if _, err := sim.Collect(ctx, m.ID); err != nil {
			return nil, fmt.Errorf("demo warm-up collect: %w", err)
		}
		if _, err := sim.Predict(ctx, m.ID); err != nil {
			return nil, fmt.Errorf("demo warm-up predict: %w", err)
		}
		res.Warmup++
	}

	pipeline, err := s.RunPipeline(ctx, m.ID)
	if err != nil {
		return nil, err
	}
	res.Pipeline = pipeline
	if m, err = s.Modules.Get(ctx, m.ID); err != nil {
		return nil, err
	}
	for _, key := range dataOf(m).SourceKeys() {
		if runs, err := s.Backtest(ctx, m.ID, key, 0); err == nil {
			res.Backtests += len(runs)
		} else if !errors.Is(err, ErrNotConfigured) {
			pipeline.Errors = append(pipeline.Errors, fmt.Sprintf("backtest %s: %v", key, err))
		}
	}
	if evaluated, err := s.Evaluate(ctx, m.ID); err == nil {
		for _, e := range evaluated {
			res.Evaluated += e.Evaluated
		}
	} else {
		pipeline.Errors = append(pipeline.Errors, "evaluate: "+err.Error())
	}
	if _, err := s.ScoreModule(ctx, m.ID); err != nil {
		pipeline.Errors = append(pipeline.Errors, "score: "+err.Error())
	}
	// a second recommendation now sees the backtests and the evaluations
	if rec, _, err := s.Recommend(ctx, m.ID); err == nil {
		pipeline.Recommend = rec
	} else {
		pipeline.Errors = append(pipeline.Errors, "recommend: "+err.Error())
	}
	return res, nil
}

func seasonParams() string {
	return fmt.Sprintf(`{"season_length_steps":%d}`, 86400/demoStepSeconds)
}

// DeleteDemo removes the demo module with its stored data, the demo mappings and the demo datasource. The algorithm
// settings are platform-wide and stay as they are. Objects that are not part of the demo are never touched.
func (s *Service) DeleteDemo(ctx context.Context) error {
	m, err := s.Modules.ByName(ctx, DemoModuleName)
	if err != nil && !errors.Is(err, gorm.ErrRecordNotFound) {
		return err
	}
	if m != nil && err == nil {
		if m.Enabled {
			m.Enabled = false
			if err := s.Modules.Update(ctx, m); err != nil {
				return err
			}
		}
		if err := s.Modules.Delete(ctx, m.ID); err != nil {
			return err
		}
		if err := s.Predictions.DeleteModuleData(ctx, m.ID); err != nil {
			return err
		}
	}
	ds, err := s.Datasources.ByName(ctx, DemoDatasourceName)
	if err != nil || ds == nil {
		return err
	}
	if ds.Type != model.DatasourceTypeDemo {
		return fmt.Errorf("datasource %q is not a demo datasource and is left alone", ds.Name)
	}
	mappings, err := s.Mappings.ListByDatasource(ctx, ds.ID)
	if err != nil {
		return err
	}
	ids := make([]uint, len(mappings))
	for i, mp := range mappings {
		ids[i] = mp.ID
	}
	if len(ids) > 0 {
		if err := s.Mappings.Delete(ctx, ids); err != nil {
			return err
		}
	}
	return s.Datasources.Delete(ctx, []uint{ds.ID})
}
